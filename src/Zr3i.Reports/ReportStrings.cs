    public static IReadOnlyDictionary<string, string> For(string language) => language == "ar" ? Arabic : English;

    public static string Text(string language, string key, params (string Name, string Value)[] vars)
    {
        var text = For(language).TryGetValue(key, out var v) ? v : key;
        foreach (var (name, value) in vars) text = text.Replace("{" + name + "}", value, StringComparison.Ordinal);
        return text;
    }
